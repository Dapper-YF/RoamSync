class ForbiddenProvider:
    async def generate(self, *args):
        raise AssertionError("saved notes must not be generated by a model")


@pytest.mark.parametrize("variant", ["pending", "accepted", "stale", "rejected", "ambiguous",
                                    "invalid", "foreign", "malformed", "timing", "unknown"])
def test_saved_notes_are_read_only_version_bound_and_not_validated_rationale(variant):
    with TestClient(app) as client:
        client.post("/api/v1/demo/reset")
        async def scenario():
            async with session_factory() as db:
                trip = await db.get(Trip, DEMO_TRIP_ID)
                place = await db.scalar(select(PlaceCandidate).where(PlaceCandidate.trip_id == trip.id).limit(1))
                trip.version = 2 if variant in {"accepted", "stale"} else 1
                run = PlanningRun(trip_id=trip.id, run_type="initial_plan", status="accepted" if variant == "accepted" else
                                  "rejected" if variant == "rejected" else "awaiting_confirmation",
                                  user_request="合成说明测试", base_trip_version=1)
                db.add(run)
                await db.flush()
                snapshot = {"explanation":"合成方案说明：先文化体验，再安排休息。", "activities":[{
                    "candidate_id":"fixture", "day_date":"2026-09-05", "place_candidate_id":str(uuid.uuid4()) if variant == "foreign" else str(place.id),
                    "planned_start_time":"10:00", "duration_minutes":60, "estimated_cost_fen":0,
                    "transport_mode_to_here":"walk", "reason":"合成保存理由：这项安排回应文化兴趣。"}]}
                revision = PlanRevision(trip_id=trip.id, planning_run_id=run.id, revision_number=1,
                    status="accepted" if variant == "accepted" else "rejected" if variant == "rejected" else "pending",
                    before_snapshot={}, proposed_snapshot={} if variant == "malformed" else snapshot,
                    validation_result={"valid":variant != "invalid"}, difference_summary={"decision_summary":{"status":"unavailable"}})
                db.add(revision)
                if variant == "ambiguous":
                    other = PlanningRun(trip_id=trip.id, run_type="initial_plan", status="awaiting_confirmation", user_request="另一份", base_trip_version=1)
                    db.add(other)
                    await db.flush()
                    db.add(PlanRevision(trip_id=trip.id, planning_run_id=other.id, revision_number=1, status="pending",
                        before_snapshot={}, proposed_snapshot=snapshot, validation_result={"valid":True}, difference_summary={}))
                await db.commit()
                message = f"为什么把{place.name}安排在18点？" if variant == "timing" else "为什么把不存在的场馆安排在上午？" if variant == "unknown" else "为什么会这样安排行程？"
                # Database-enforced read-only transaction: any mutation fails.
                await db.execute(text("SET TRANSACTION READ ONLY"))
                result = await CompanionRuntime(CompanionContextReader(db, trip.id), ForbiddenProvider()).run(
                    session_id="fixture-session", turn_id="fixture-turn", message=message,
                    goal=route_travel_goal(message), messages=[])
                if variant in {"pending", "accepted"}:
                    assert result.explanation.explanation_type == "saved_plan_notes"
                    assert result.explanation.source_decision_ref == "revision:" + str(revision.id)
                    assert result.explanation.based_on_prior_decision is False
                    assert "文化兴趣" in result.response_text
                    assert "未作为已验证" in result.response_text
                    assert ("待确认候选" if variant == "pending" else "已接受") in result.response_text
                else:
                    assert result.explanation.explanation_type == "rationale_unavailable"
        asyncio.run(scenario())


def test_saved_notes_cannot_claim_verified_original_decision():
    with pytest.raises(ValueError):
        CompanionExplanation(explanation_type="saved_plan_notes", reasons=["说明"], based_on_prior_decision=True)
    with pytest.raises(ValueError):
        CompanionExplanation(explanation_type="saved_plan_notes", reasons=["说明"])


def test_companion_question_preserves_current_planning_run_binding():
    with TestClient(app) as client:
        client.post("/api/v1/demo/reset")
        async def scenario():
            async with session_factory() as db:
                run = PlanningRun(trip_id=DEMO_TRIP_ID, run_type="initial_plan", status="awaiting_confirmation",
                                  user_request="合成任务", base_trip_version=1)
                db.add(run)
                await db.flush()
                row = await get_or_create_session(db, DEMO_TRIP_ID)
                row.latest_run_id = run.id
                await db.commit()
                # No saved revision: honest fallback still preserves UI identity.
                row = await send_message(db, row.id, "为什么会这样安排？", uuid.uuid4(), companion_provider=ForbiddenProvider())
                assert row.latest_run_id == run.id
                assert row.messages[-1]["run_id"] is None
                assert row.messages[-1]["companion_result"]["explanation"]["explanation_type"] == "rationale_unavailable"
        asyncio.run(scenario())
